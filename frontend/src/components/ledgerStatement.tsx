import type { LedgerEntry } from "../types";

/** The facts at the top of a ledger statement, in the CSV and on the printed page. */
export interface StatementInfo {
  /** YYYY-MM-DD */
  reportDate: string;
  address: string;
  unit: string;
  tenants: string[];
  /** The manager who made it; left out of a tenant's own copy. */
  generatedBy?: { name: string; email: string };
}

const TYPE_LABELS = { charge: "Charge", payment: "Payment", refund: "Refund" } as const;

/** Rows for `downloadCsv`: the facts, a blank row, then every ledger line, oldest first. */
export function ledgerStatementRows(info: StatementInfo, ledger: LedgerEntry[]): Array<Array<string | number>> {
  return [
    ["Report Date", info.reportDate],
    ["Report Period", "All time"],
    ["Property Address", info.address],
    ["Unit #", info.unit],
    ...info.tenants.map((name, i) => [i === 0 ? "Tenants" : "", name]),
    ...(info.generatedBy ? [["Generated By", info.generatedBy.name], ["Manager Email", info.generatedBy.email]] : []),
    [],
    ["Type", "Date", "Description", "Charges", "Payments", "Balance", "Payment Method"],
    // The ledger is newest first; a statement reads oldest first. Amounts stay numbers so a refund keeps its minus sign.
    ...[...ledger].reverse().map((e) => [
      TYPE_LABELS[e.type],
      e.isoDate,
      e.description,
      e.type === "charge" ? -e.amount : 0,
      e.type === "charge" ? 0 : e.amount,
      e.balanceAfter,
      e.method ?? "",
    ]),
  ];
}

/** The same facts as a block that shows only when the page is printed. */
export function LedgerStatementHead({ info }: { info: StatementInfo }) {
  const facts: Array<[string, string]> = [
    ["Report date", info.reportDate],
    ["Property address", info.address],
    ["Unit", info.unit],
    ["Tenants", info.tenants.join(", ")],
    ...(info.generatedBy ? [["Generated by", `${info.generatedBy.name} (${info.generatedBy.email})`] as [string, string]] : []),
  ];
  return (
    <dl className="print-only statement-head">
      {facts.map(([label, value]) => (
        <div key={label}>
          <dt>{label}</dt>
          <dd>{value}</dd>
        </div>
      ))}
    </dl>
  );
}
